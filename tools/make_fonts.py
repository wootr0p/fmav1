"""FMav-1's anti-aliased fonts: Inter Tight (The Inter Project Authors, SIL OFL 1.1: assets/fonts/InterTight-OFL.txt)
rasterised at a few sizes and weights into 4-bit coverage tables -> firmware/gen/mfm_fonts.h (committed; the tables are
not offered as a font). Needs Pillow.

  tools/make_fonts.py [out.h]

Each font: ASCII 32..126 (FA_SPLASH: only the splash's letters), per glyph its box (w, h), its offset from the pen
(x right, y down from the top of the line) and its advance; the coverage 0..15 two pixels a byte, rows padded to a byte."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / "assets" / "fonts" / "InterTight-wght.ttf"
# name, pixel size, weight, characters (None: ASCII 32..126)
FONTS = [
    ("FA8", 8, 650, None),          # the tabs, small captions
    ("FA10", 10, 620, None),        # knob labels, values, the footer
    ("FA12", 12, 640, None),        # titles, the tags
    ("FA16", 16, 680, None),        # the program's name
    ("FA26", 26, 720, "0123456789-?"),   # the program's number
    ("FA40", 40, 300, "FMAV-1 "),        # the splash
]


def font_of(size, wght):
    f = ImageFont.truetype(str(TTF), size)
    f.set_variation_by_axes([wght])
    return f


def build(name, size, wght, chars):
    f = font_of(size, wght)
    asc, desc = f.getmetrics()
    chars = chars or "".join(chr(c) for c in range(32, 127))
    glyphs, data = [], bytearray()
    for ch in chars:
        x0, y0, x1, y1 = f.getbbox(ch, anchor="la")
        adv = int(round(f.getlength(ch)))
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="la")
            px = im.load()
            for y in range(h):
                row = [min(15, (px[x, y] + 8) // 17) for x in range(w)]
                if len(row) % 2:
                    row.append(0)
                for i in range(0, len(row), 2):
                    data.append(row[i] << 4 | row[i + 1])
        glyphs.append((off, w, h, x0, y0, adv, ch))
    return asc, desc, chars, glyphs, data


def main(out):
    L = ["/* generated by tools/make_fonts.py from Inter Tight (The Inter Project Authors, SIL OFL 1.1,",
         " * assets/fonts/InterTight-OFL.txt): do not edit */", "#pragma once", "#include <stdint.h>",
         "typedef struct { uint16_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; } aglyph_t;",
         "typedef struct { const aglyph_t *g; const uint8_t *px; const char *map; uint8_t asc, line; } afont_t;", ""]
    for name, size, wght, chars in FONTS:
        asc, desc, cs, glyphs, data = build(name, size, wght, chars)
        L.append(f"static const uint8_t {name}_PX[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            L.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        if not data:
            L.append("    0,")
        L.append("};")
        L.append(f"static const aglyph_t {name}_G[{len(glyphs)}] = {{")
        for off, w, h, xo, yo, adv, ch in glyphs:
            c = ch.replace("\\", "\\\\").replace("*/", "* /")
            L.append(f"    {{{off}, {w}, {h}, {xo}, {yo}, {adv}}},  /* {c} */")
        L.append("};")
        mp = "0" if chars is None else '"' + cs.replace("\\", "\\\\").replace('"', '\\"') + '"'
        L.append(f"static const afont_t {name} = {{{name}_G, {name}_PX, {mp}, {asc}, {asc + desc}}};")
        L.append("")
        print(f"{name}: {len(glyphs)} glyphs, {len(data)} B, ascent {asc}, line {asc + desc}")
    Path(out).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "firmware" / "gen" / "mfm_fonts.h"))
